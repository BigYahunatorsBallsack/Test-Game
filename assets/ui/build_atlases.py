"""Pack the approved individual PNGs and verify the catalogue associations."""

import json
from collections import Counter
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets"
DEST = ASSETS / "ui"
MODULES = ROOT / "src/client/Interface"
ZONE_ORDER = ("duenenmeer", "oase", "canyon", "salzsee", "ruinenstadt")
CELL, PAD = 80, 4


def read(path):
    return json.loads((ASSETS / path).read_text(encoding="utf-8"))


draft = read("reference/finds_draft.json")["items"]
match = read("studio/find_model_map.json")["items"]
by_id = {item["id"]: item for item in match}
assert len(draft) == len(match) == len(by_id) == len({item["id"] for item in draft}) == 150
assert set(by_id) == {item["id"] for item in draft}
assert len({item["path"] for item in match}) == len({item["source_icon"] for item in match}) == 150
assert Counter(item["zone"] for item in draft) == dict.fromkeys(ZONE_ORDER, 30)
assert len(Counter(item["set_id"] for item in draft)) == 30
assert set(Counter(item["set_id"] for item in draft).values()) == {5}
groups = {
    "Core": sorted(path for group in ("tools", "storage", "selling", "luck", "crates", "currency", "frames")
                   for path in (ASSETS / "icons" / group).glob("*.png")),
}
rows = {zone: [] for zone in ZONE_ORDER}
model_rows = []
for find in draft:
    item = by_id[find["id"]]
    zone = find["zone"]
    assert item["zone"] == zone and item["source_icon"] == find["icon_path"]
    assert item["name_de"] == find["name_de"] and item["set_id"] == find["set_id"]
    assert item["path"] == f"ServerStorage.DuneBaronAssetLibrary.Finds.{zone}.{find['id']}"
    groups.setdefault(zone, []).append(ROOT / find["icon_path"])
    rows[zone].append({
        "id": find["id"], "name": find["name_de"], "description": find["description_de"],
        "set": find["set_name"], "rarity": find["rarity"], "icon": find["id"],
    })
    model_rows.append({"id": find["id"], "zone": zone, "model": item["path"], "icon": find["icon_path"]})
assert len(groups["Core"]) == 35


def quote(text):
    return json.dumps(text, ensure_ascii=False)


MODULES.mkdir(parents=True, exist_ok=True)
pages, icons = {}, {}
for key, paths in groups.items():
    cols = 7 if key == "Core" else 6
    height = ((len(paths) + cols - 1) // cols) * CELL
    atlas = Image.new("RGBA", (CELL * cols, height))
    for i, path in enumerate(paths):
        with Image.open(path) as source:
            image = source.convert("RGBA")
        original = image.getchannel("A")
        assert original.getextrema()[0] == 0 and original.getextrema()[1] >= 200, path
        bbox = original.point(lambda x: 255 if x >= 55 else 0).getbbox()
        assert bbox is not None
        image = image.crop(bbox if key != "Core" else original.getbbox())
        image.thumbnail((CELL - 2 * PAD, CELL - 2 * PAD), Image.Resampling.LANCZOS)
        x, y = i % cols * CELL, i // cols * CELL
        atlas.alpha_composite(image, (x + (CELL-image.width)//2, y + (CELL-image.height)//2))
        ident = path.stem.removesuffix("_01") if key == "Core" else rows[key][i]["id"]
        assert ident not in icons
        icons[ident] = (key,x,y)
    atlas.save(DEST / f"Atlas_{key}.png", optimize=True)
    pages[key] = atlas.size
assert len(icons)==185

lines = ["-- Generated by assets/ui/build_atlases.py", "return {", f"    cell = {CELL},", "    pages = {"]
for name, (w,h) in pages.items():
    lines.append(f"        {name} = {{width={w},height={h}}},")
lines += ["    },", "    icons = {"]
for name,(page,x,y) in icons.items():
    lines.append(f"        {name} = {{page={quote(page)},x={x},y={y}}},")
lines += ["    },", "    finds = {"]
for zone, records in rows.items():
    lines.append(f"        {zone} = {{")
    for record in records:
        fields = ", ".join(f"{k}={quote(v)}" for k,v in record.items())
        lines.append(f"            {{{fields}}},")
    lines.append("        },")
lines += ["    },", "}", ""]
(MODULES / "Catalog.luau").write_text("\n".join(lines),encoding="utf-8")
(DEST / "collection_assets.json").write_text(json.dumps(model_rows,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
print(f"{len(icons)} icons across {len(pages)} atlases. {len(model_rows)} unique model-to-icon pairs.")
